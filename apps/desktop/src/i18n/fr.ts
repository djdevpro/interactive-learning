/**
 * French punctuation keeps its spaces, which no line break may split: a no-break space before a
 * colon and inside « », a narrow one before ; ! and ?. The catalog is written with plain spaces.
 */
export function typeset(text: string): string {
  return text
    .replace(/ :/g, ' :')
    .replace(/ ([;!?])/g, ' $1')
    .replace(/« /g, '« ')
    .replace(/ »/g, ' »');
}

